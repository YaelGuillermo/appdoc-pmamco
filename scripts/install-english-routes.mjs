import {
  existsSync,
  readFileSync,
  writeFileSync,
  rmSync,
  mkdirSync,
  copyFileSync,
  readdirSync,
} from 'node:fs';
import { resolve, join, dirname } from 'node:path';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';

const root = resolve(process.cwd());
const mode = process.argv[2];
if (!['--dry-run', '--apply'].includes(mode)) throw new Error('Usa --dry-run o --apply.');
const apply = mode === '--apply';
const mapping = {
  'primer-acceso-e-idioma': 'first-access-and-language',
  'explora-la-pantalla-inicial': 'explore-the-home-screen',
  'crea-y-administra-columnas': 'create-and-manage-columns',
  'estructura-y-movimiento-de-tarjetas': 'card-structure-and-movement',
  'conoce-el-interior-de-una-tarjeta': 'explore-a-card',
  'escribe-y-publica-comentarios': 'write-and-publish-comments',
  'edita-y-archiva-comentarios': 'edit-and-archive-comments',
  'mueve-y-reasigna-tarjetas': 'move-and-reassign-cards',
  'notas-y-ultimos-elementos': 'notes-and-final-elements',
  'localiza-la-tarea-y-su-reloj': 'find-the-task-and-clock',
  'comienza-a-registrar-tiempo': 'start-tracking-time',
  'pausa-y-continua-despues': 'pause-and-resume-later',
  'finaliza-la-tarea': 'finish-the-task',
  'interpreta-los-intervalos': 'understand-time-intervals',
  'corrige-el-ultimo-intervalo': 'correct-the-latest-interval',
  'revisa-y-edita-el-historial': 'review-and-edit-history',
  'evita-cambiar-varias-tareas': 'avoid-changing-multiple-tasks',
  'practica-con-dos-dias': 'practice-across-two-days',
};
const source = [
  [
    'src/content/tutorials/es/bienvenida-gestor-tareas.md',
    'bienvenida-gestor-tareas',
    'welcome-task-manager',
  ],
  ...Object.entries(mapping).map(([oldSlug, newSlug]) => {
    for (const folder of ['bienvenida-gestor-tareas', 'registrar-tiempo']) {
      const path = join(root, 'src/content/lessons/es', folder);
      if (!existsSync(path)) continue;
      // No cambian IDs internos de Astro ni nombres físicos de los archivos.
      const files = readdirSync(path).filter((name) => name.endsWith('.md'));
      for (const name of files) {
        const rel = `src/content/lessons/es/${folder}/${name}`;
        const text = readFileSync(join(root, rel), 'utf8');
        if (new RegExp(`^slug: (?:${oldSlug}|${newSlug})$`, 'm').test(text))
          return [rel, oldSlug, newSlug];
      }
    }
    throw new Error(`No se encontró el paso: ${oldSlug}`);
  }),
];

const obsolete = [
  'src/pages/[locale]/tutorials/[tutorial]/index.astro',
  'src/pages/[locale]/tutorials/[tutorial]/[lesson].astro',
  'src/pages/[locale]/platforms/index.astro',
  'src/pages/[locale]/platforms/[platform]/index.astro',
  'src/pages/[locale]/platforms/[platform]/tutorials/[tutorial]/index.astro',
  'src/pages/[locale]/platforms/[platform]/tutorials/[tutorial]/[lesson].astro',
];
const modified = [];
for (const [rel, oldSlug, newSlug] of source) {
  const path = join(root, rel);
  if (!existsSync(path)) throw new Error(`Falta ${rel}. Instala antes Bienvenida y V2.`);
  const previous = readFileSync(path, 'utf8');
  const hasOld = new RegExp(`^slug: ${oldSlug}$`, 'm').test(previous);
  const hasNew = new RegExp(`^slug: ${newSlug}$`, 'm').test(previous);
  if (!hasOld && !hasNew) throw new Error(`${rel}: slug inesperado`);
  const expected = hasOld
    ? previous.replace(new RegExp(`^slug: ${oldSlug}$`, 'm'), `slug: ${newSlug}`)
    : previous;
  if (expected !== previous) modified.push({ rel, previous, expected });
}
const removed = obsolete.filter((file) => existsSync(join(root, file)));
const redirectsPath = join(root, 'public/_redirects');
if (!existsSync(redirectsPath)) throw new Error('Falta public/_redirects: extrae el ZIP antes.');
const priorRedirects = readFileSync(redirectsPath, 'utf8');
const marker = '# English-only lesson aliases generated by install-english-routes.mjs';
const aliases = [];
for (const [old, target] of Object.entries(mapping)) {
  // Los slugs son únicos, y la ruta nueva resuelve en el producto.
  const legacyTutorial = [
    'first-access-and-language',
    'explore-the-home-screen',
    'create-and-manage-columns',
    'card-structure-and-movement',
    'explore-a-card',
    'write-and-publish-comments',
    'edit-and-archive-comments',
    'move-and-reassign-cards',
    'notes-and-final-elements',
  ].includes(target)
    ? 'bienvenida-gestor-tareas'
    : 'time-tracking';
  const targetTutorial =
    legacyTutorial === 'bienvenida-gestor-tareas' ? 'welcome-task-manager' : 'time-tracking';
  for (const prefix of [
    `/es/tutorials/${legacyTutorial}/`,
    `/es/platforms/pm-amco-editorial/tutorials/${legacyTutorial}/`,
    `/es/pm-amco-editorial/tutorials/${targetTutorial}/`,
  ]) {
    aliases.push(
      `${prefix}${old}/ /es/pm-amco-editorial/tutorials/${targetTutorial}/${target}/ 301`,
    );
  }
}
const expectedRedirects = priorRedirects.includes(marker)
  ? priorRedirects
  : `${priorRedirects.trimEnd()}\n${marker}\n${aliases.join('\n')}\n`;
const redirectsChanged = expectedRedirects !== priorRedirects;
console.log(
  `[routes] ${modified.length} slugs por traducir, ${removed.length} páginas antiguas por retirar, redirecciones: ${redirectsChanged ? 'añadir' : 'OK'}`,
);
if (!apply) process.exit(0);
const allBackups = [
  ...modified.map((x) => x.rel),
  ...removed,
  ...(redirectsChanged ? ['public/_redirects'] : []),
];
if (!allBackups.length) {
  console.log('[routes] Ya aplicado.');
  process.exit(0);
}
const backup = mkdtempSync(join(tmpdir(), 'amco-routes-'));
for (const rel of allBackups) {
  const to = join(backup, rel);
  mkdirSync(dirname(to), { recursive: true });
  copyFileSync(join(root, rel), to);
}
try {
  for (const item of modified) writeFileSync(join(root, item.rel), item.expected);
  if (redirectsChanged) writeFileSync(redirectsPath, expectedRedirects);
  for (const rel of removed) rmSync(join(root, rel));
} catch (error) {
  for (const rel of allBackups) {
    const to = join(root, rel);
    mkdirSync(dirname(to), { recursive: true });
    copyFileSync(join(backup, rel), to);
  }
  throw error;
}
console.log(`[routes] Instalado. Respaldo: ${backup}`);
